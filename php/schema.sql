CREATE DATABASE IF NOT EXISTS fempro CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE fempro;
CREATE TABLE users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE,
 whatsapp VARCHAR(30) NOT NULL, password_hash VARCHAR(255) NOT NULL, slug VARCHAR(100) NOT NULL UNIQUE,
 niche VARCHAR(100) NOT NULL, city VARCHAR(140) DEFAULT '', bio TEXT, photo VARCHAR(255), plan ENUM('free','premium') NOT NULL DEFAULT 'free',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE services (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL, name VARCHAR(140) NOT NULL,
 duration SMALLINT UNSIGNED NOT NULL DEFAULT 60, price DECIMAL(10,2) NOT NULL DEFAULT 0, category VARCHAR(100) DEFAULT '',
 active TINYINT(1) NOT NULL DEFAULT 1, FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE appointments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL, service_id BIGINT UNSIGNED NOT NULL,
 client_name VARCHAR(120) NOT NULL, client_whatsapp VARCHAR(30) NOT NULL, appointment_date DATE NOT NULL,
 start_time TIME NOT NULL, status ENUM('pendente','confirmado','concluido','cancelado') NOT NULL DEFAULT 'pendente',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(service_id) REFERENCES services(id) ON DELETE CASCADE, INDEX(user_id,appointment_date,start_time)
) ENGINE=InnoDB;
CREATE TABLE working_hours (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL, weekday TINYINT UNSIGNED NOT NULL,
 enabled TINYINT(1) NOT NULL DEFAULT 1, start_time TIME NOT NULL DEFAULT '09:00:00', end_time TIME NOT NULL DEFAULT '19:00:00',
 UNIQUE KEY(user_day(user_id,weekday)), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE preferences (
 user_id BIGINT UNSIGNED PRIMARY KEY, whatsapp_notifications TINYINT(1) NOT NULL DEFAULT 1,
 daily_email TINYINT(1) NOT NULL DEFAULT 0, auto_confirm TINYINT(1) NOT NULL DEFAULT 1,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
